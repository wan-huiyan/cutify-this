#!/usr/bin/env python3
"""Assemble a self-contained, still-interactive demo-standalone.html from the
sparkle-that-page examples — the single-file artifact you upload to Claude Design.

It inlines cute_chrome.css, embeds each effect's source in a non-executing
<script type="text/plain"> block, rewires the demo's enable() to inject that
inline source (no external fetches), and turns every effect on at load so the
mockup shows the magic live. Re-run after editing any effect file.
"""
import re, pathlib

BASE = pathlib.Path("plugins/sparkle-that-page/skills/sparkle-that-page/examples")
OUT = pathlib.Path("docs/design-handoff/demo-standalone.html")
EFFECTS = {
    "fairyCursor": "fairy_cursor.js",
    "sparkleTrail": "sparkle_trail.js",
    "scrollIndicator": "scroll_indicator.js",
    "tabPeekaboo": "tab_title_peekaboo.js",
    "clickConfetti": "click_confetti.js",
    "ambientFloaters": "ambient_floaters.js",
}

demo = (BASE / "demo.html").read_text()
css = (BASE / "cute_chrome.css").read_text()

# 1. inline the stylesheet
demo, n = re.subn(r'<link rel="stylesheet" href="\./cute_chrome\.css">',
                  "<style>\n" + css + "\n</style>", demo)
assert n == 1, "cute_chrome.css <link> not found"

# 2. rewire enable() to inject inlined source instead of fetching ./file.js
old_enable = ('      var s = document.createElement("script");\n'
              '      s.src = "./" + eff.file + "?v=" + (++injCount);\n'
              '      s.setAttribute("data-stp", eff.key);\n'
              '      document.body.appendChild(s);')
new_enable = ('      var src = document.getElementById("src-" + eff.key);\n'
              '      var s = document.createElement("script");\n'
              '      s.textContent = src ? src.textContent : "";\n'
              '      s.setAttribute("data-stp", eff.key);\n'
              '      document.body.appendChild(s);')
assert old_enable in demo, "enable() block not found — did demo.html change?"
demo = demo.replace(old_enable, new_enable)

# 3. embed each effect's source as a non-executing text/plain block.
#    Escape any </script in the source (only ever in the comment-header usage
#    example) so it can't close the embedding block early; "<\/script" is an
#    escaped slash inside a JS comment, harmless when the source is re-executed.
def embed(fn):
    src = (BASE / fn).read_text()
    return re.sub(r"(?i)</script", r"<\\/script", src)
blocks = "\n".join(
    '<script type="text/plain" id="src-%s">\n%s\n</script>' % (key, embed(fn))
    for key, fn in EFFECTS.items())
marker = "  <script>\n    // Each effect:"
assert marker in demo, "controller <script> marker not found"
demo = demo.replace(marker, blocks + "\n" + marker, 1)

# 4. turn every effect on at load so the uploaded mockup shows the magic live
on_all = ('\n    // standalone artifact: show every effect live on load\n'
          '    EFFECTS.forEach(function (eff) { var c = document.getElementById("chk-" + eff.key); if (c) { c.checked = true; enable(eff); } });\n')
demo = demo.replace("  </script>\n</body>", on_all + "  </script>\n</body>", 1)

# 5. mark the file's purpose in the title comment
demo = demo.replace("<head>", "<head>\n  <!-- SELF-CONTAINED upload artifact for Claude Design — generated by docs/design-handoff/build_standalone.py. No external fetches. -->", 1)

OUT.write_text(demo)
print("wrote", OUT, "(%d bytes)" % len(demo))
