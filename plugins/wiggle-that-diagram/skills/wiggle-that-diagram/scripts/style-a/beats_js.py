#!/usr/bin/env python3
# Style A timing bridge: writes engine/ways/<film>_beats.js (window.<VAR> = the film's beats from beats.json) so the scene file reads captions and timing from the one shared script instead of a hand copy. Inputs: beats.json, engine dir.
"""python3 beats_js.py beats.json --engine engine [--var PZ_BEATS]
Writes one file per film: engine/ways/<film>_beats.js with window.<VAR> = [{title, caption, dur, still}, ...] (VAR defaults to
<FILM>_BEATS in capitals). List it in SCENE_LIBS before the scene file, then in the scene:
  WAY.make({ poster: [k, B[k-1].still], beats: B.map(b => ({ title: b.title, dur: b.dur, cap: b.caption, still: b.still })), ... })
Runs the common pacing gate first (exit 1 if a beat is short). Re-run after any change to beats.json, then re-render."""
import argparse, json, pathlib, subprocess, sys
ap = argparse.ArgumentParser(); ap.add_argument('beats'); ap.add_argument('--engine', default='engine'); ap.add_argument('--var'); a = ap.parse_args()
gate = pathlib.Path(__file__).resolve().parent.parent / 'common' / 'pace_check.py'
ok = subprocess.run([sys.executable, str(gate), a.beats]).returncode == 0
for film, spec in json.loads(pathlib.Path(a.beats).read_text()).items():
    if film.startswith('_'): continue
    var = a.var or f'{film.upper()}_BEATS'
    rows = [dict(title=b['title'], caption=b['caption'], dur=b['dur'], still=b['still']) for b in spec['beats']]
    out = pathlib.Path(a.engine) / 'ways' / f'{film}_beats.js'; out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f'// generated by beats_js.py from {pathlib.Path(a.beats).name}, do not edit\nwindow.{var} = {json.dumps(rows, ensure_ascii=False)};\n')
    print(f'{out}: window.{var}, {len(rows)} beats')
sys.exit(0 if ok else 1)
