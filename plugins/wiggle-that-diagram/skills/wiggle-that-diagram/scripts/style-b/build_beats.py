#!/usr/bin/env python3
# Style B timing bridge: runs the common pacing gate on beats.json, then writes engine/demos/<film>/beats.js (window.BEATS) for the board code. Inputs: beats.json, engine dir.
"""python3 build_beats.py beats.json --engine engine
beats.json is the single source of timing (format: ../common/beats.example.json). The board code anchors every event as
B.at(BEATS[k].t0 + offset), so a beat's length can change here without retiming the others. Re-render after any change."""
import argparse, json, pathlib, subprocess, sys
ap = argparse.ArgumentParser(); ap.add_argument('beats'); ap.add_argument('--engine', default='engine'); a = ap.parse_args()
gate = pathlib.Path(__file__).resolve().parent.parent / 'common' / 'pace_check.py'
ok = subprocess.run([sys.executable, str(gate), a.beats]).returncode == 0
D = json.loads(pathlib.Path(a.beats).read_text())
for film, spec in D.items():
    if film.startswith('_'): continue
    t, out = 0.0, []
    for i, b in enumerate(spec['beats'], 1):
        out.append({'n': i, 't0': round(t, 3), 't1': round(t + b['dur'], 3), 'still': round(t + b['still'], 3)})
        t += b['dur']
    d = pathlib.Path(a.engine) / 'demos' / film; d.mkdir(parents=True, exist_ok=True)
    (d / 'beats.js').write_text(f'// generated by build_beats.py from {pathlib.Path(a.beats).name}, do not edit\nwindow.BEATS = {json.dumps(out)};\nwindow.FILM_TOTAL = {round(t, 3)};\n')
    print(f'{d / "beats.js"}: {len(out)} beats, {t:.1f} s')
sys.exit(0 if ok else 1)
